from rest_framework import generics
from .models import User, Empleado
from .serializers import UserSerializer, EmpleadoSerializer

# --- VISTAS PARA USER (Las que ya estaban) ---
class UserList(generics.ListCreateAPIView):
    queryset = User.objects.all()
    serializer_class = UserSerializer

class UserDetail(generics.RetrieveAPIView):
    queryset = User.objects.all()
    serializer_class = UserSerializer

# --- VISTAS PARA EMPLEADO (Las tuyas) ---
class EmpleadoList(generics.ListCreateAPIView):
    queryset = Empleado.objects.all()
    serializer_class = EmpleadoSerializer

class EmpleadoDetail(generics.RetrieveUpdateDestroyAPIView):
    queryset = Empleado.objects.all()
    serializer_class = EmpleadoSerializer